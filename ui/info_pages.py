def render_about(language: str) -> None:
    st.markdown(
        """
## About AgriBot AI

AgriBot AI answers farming questions in **English and Tamil** using
**Retrieval-Augmented Generation (RAG)**: it first searches a small, curated library of
agricultural documents from the **Tamil Nadu Agricultural University (TNAU) Agritech
Portal**, then asks a language model to explain only what those passages say, with
citations.

**Topics covered by the current knowledge base**
- Irrigation: critical stages, drip and sprinkler irrigation, irrigation water quality
- Nutrients and soil: integrated nutrient management, fertilizer application methods and
  efficiency, essential elements, deficiency symptoms, organic matter
- Rice (paddy): System of Rice Intensification (SRI) nursery, water and weed management
- Crop protection: integrated pest management (IPM), natural pest control, major rice
  pests (stem borer, gall midge, leaf folder) and diseases (blast, brown spot, bacterial
  leaf blight, sheath blight)
- Crop selection

**Important disclaimer**: AgriBot AI is an educational project. It is not a substitute
for advice from qualified agricultural officers. Diagnoses from text descriptions are
never certain. Source content belongs to its publishers (TNAU and others) and is shown
here with attribution for non-commercial educational use.
"""
    )


def render_project_info(settings_view: dict[str, Any], kb_info: dict[str, Any]) -> None:
    st.markdown("## Project information")
    st.markdown(
        """
**Pipeline**: question → input validation → language detection → multilingual embedding
(language-centred) + character n-gram lexical scoring → hybrid ranking → code-enforced
relevance threshold → grounded prompt with delimited evidence → LLM → citation/URL/quantity
validation → sources rendered from stored metadata.

**Technology**: Python · Streamlit · sentence-transformers
(`paraphrase-multilingual-MiniLM-L12-v2`) · FAISS · PyMuPDF · NumPy · pytest ·
OpenAI-compatible hosted LLM API or local Ollama.
"""
    )
    col1, col2 = st.columns(2)
    with col1:
        st.markdown("**Knowledge base**")
        st.json(kb_info, expanded=True)
    with col2:
        st.markdown("**Runtime configuration** (secrets hidden)")
        st.json(settings_view, expanded=True)
    st.caption(
        "Measured retrieval results are in evaluation/results/. No end-to-end answer "
        "accuracy percentage is claimed."
    )
